import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join } from 'node:path';
import * as anchor from '@coral-xyz/anchor';
import { Connection, Keypair } from '@solana/web3.js';
import { getAccount, getAssociatedTokenAddress } from '@solana/spl-token';
import { AgentBondClient } from '../packages/sdk/src/index.ts';
const connection = new Connection('http://127.0.0.1:8899','confirmed');
const signer = Keypair.fromSecretKey(Uint8Array.from(JSON.parse(await readFile(join(process.env.AGENTBOND_KEY_DIR ?? join(homedir(),'.agentbond','keys'),'worker.json'),'utf8'))));
const sdk = new AgentBondClient(connection,new anchor.Wallet(signer));
const address = process.argv[2]; if (!address) throw new Error('Provide the explicit verified local job address');
const job = await sdk.getJob(address); assert(job?.status==='VERIFIED'); assert.equal(job.worker,signer.publicKey.toBase58());
const destination = await getAssociatedTokenAddress(new (await import('@solana/web3.js')).PublicKey(job.mint),signer.publicKey);
const workerBefore = (await getAccount(connection,destination)).amount;
const vaultBefore = (await getAccount(connection,new (await import('@solana/web3.js')).PublicKey(job.vault))).amount;
const signature = await sdk.settleJob(address,destination);
const workerAfter = (await getAccount(connection,destination)).amount;
const vaultAfter = (await getAccount(connection,new (await import('@solana/web3.js')).PublicKey(job.vault))).amount;
assert.equal(workerAfter-workerBefore,BigInt(job.amount)); assert.equal(vaultBefore-vaultAfter,BigInt(job.amount));
assert.equal((await sdk.getJob(address))?.status,'SETTLED');
await assert.rejects(()=>sdk.settleJob(address,destination));
const evidence={time:new Date().toISOString(),network:'localnet',address,signature,amount:job.amount,workerBefore:workerBefore.toString(),workerAfter:workerAfter.toString(),vaultBefore:vaultBefore.toString(),vaultAfter:vaultAfter.toString(),doubleSettlementRejected:true};
await writeFile(`.orchestrator/live-settlement-${address}.json`,JSON.stringify(evidence,null,2));
console.log(JSON.stringify(evidence));
